/* 렌더링: 카드들을 위에서 아래로, 클릭하면 풀이 펼침 */
(function renderSentences() {
  const body = document.getElementById("sentBody");
  if (!body) return;
  body.innerHTML = SENTENCES.map(s => `
    <div class="sent-card masked">
      <button class="sent-hide" type="button" title="히라가나·뜻 가리기">あ</button>
      <div class="sent-jp">${s.jp}</div>
      <div class="sent-hira">${s.hira}</div>
      <div class="sent-kr">${s.kr}</div>
      <div class="sent-notes">
        <div class="notes-label">단어</div>
        ${s.words.map(w => `<div class="note-item"><b>${w.w}</b> — ${w.m}</div>`).join("")}
        <div class="notes-label">문법</div>
        ${s.grammar.map(g => `<div class="note-item"><b>${g.g}</b> — ${g.m}</div>`).join("")}
      </div>
    </div>`).join("");
  body.querySelectorAll(".sent-card").forEach(card => {
    card.addEventListener("click", () => card.classList.toggle("open"));
    const hideBtn = card.querySelector(".sent-hide");
    hideBtn.addEventListener("click", (e) => {
      e.stopPropagation();                 // 카드 펼침과 분리
      card.classList.toggle("masked");     // 히라가나·뜻 숨김 토글
    });
  });
})();
